#!/usr/bin/env python3
"""One-off PDF to text with page locators. Never on the request path.

Usage: python3 scripts/parse_pdf.py "content/private/A3 MATH4430_6602.pdf" content/source.md
       python3 scripts/parse_pdf.py --sync content/source.md content/unit.json   (after hand-fixing source.md)

       python3 scripts/parse_pdf.py --sql content/unit.json content/seed_pack.sql   (rebuild the SQL after --sync)

Uses Docling if it is importable, otherwise `pdftotext -layout` (poppler).
Docling (MIT, 2.149.0 on PyPI) pulls in torch, so the fallback is the default today.
Output has one "<!-- page N -->" marker per page. Formulas come out damaged
(fractions, sums and limits split across lines); fix them by hand in source.md.
"""
import json
import subprocess
import sys


def pages_docling(pdf):
    from docling.document_converter import DocumentConverter  # unverified API, not run here

    doc = DocumentConverter().convert(pdf).document
    return [doc.export_to_markdown(page_no=n) for n in sorted(doc.pages)]


def pages_pdftotext(pdf):
    out = subprocess.run(["pdftotext", "-layout", pdf, "-"], check=True, capture_output=True, text=True).stdout
    return out.split("\f")[:-1]  # pdftotext ends every page, including the last, with \f


def normalize(text):
    """Trim lines and collapse spaces so quotes are not broken by layout padding. content/unit_test.go mirrors this."""
    lines = [" ".join(l.split()) for l in text.split("\n")]
    return "\n".join(l for l in lines if l)


def sync(src, unit):
    """Copy normalized source.md into sources[0].text of unit.json."""
    with open(unit) as f:
        data = json.load(f)
    data["sources"][0]["text"] = normalize(open(src).read())
    with open(unit, "w") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"synced {src} into {unit}")


def q(v):
    return "'" + str(v).replace("'", "''") + "'"


def sql(unit, dest):
    """Write INSERTs for the subject, source, concepts and claims. Safe to run twice."""
    u = json.load(open(unit))
    s, src = u["subject"], u["sources"][0]
    assert "$src$" not in src["text"]
    out = [
        "-- Generated by scripts/parse_pdf.py --sql from content/unit.json. Do not edit by hand.",
        "-- Load before content/seed.sql. Safe to run twice.",
        "INSERT INTO users (id, name) VALUES ('00000000-0000-0000-0000-000000000001', 'Demo Student') ON CONFLICT (id) DO NOTHING;",
        f"INSERT INTO subjects (id, user_id, name, weekly_hours, level, exam_date, weight) VALUES ({q(s['id'])}, '00000000-0000-0000-0000-000000000001', {q(s['name'])}, {s['weekly_hours']}, {q(s['level'])}, {q(s['exam_date'][:10])}, {s['weight']}) ON CONFLICT (id) DO NOTHING;",
        f"INSERT INTO sources (id, kind, title, text) VALUES ({q(src['id'])}, {q(src['kind'])}, {q(src['title'])}, $src${src['text']}$src$) ON CONFLICT (id) DO NOTHING;",
    ]
    for c in u["concepts"]:
        out.append(f"INSERT INTO concepts (id, subject_id, name) VALUES ({q(c['id'])}, {q(c['subject_id'])}, {q(c['name'])}) ON CONFLICT (id) DO NOTHING;")
        for k in c["claims"]:
            out.append(f"INSERT INTO claims (id, concept_id, text, source_id, locator, required) VALUES ({q(k['id'])}, {q(k['concept_id'])}, {q(k['text'])}, {q(k['source_id'])}, {q(k['locator'])}, {str(k['required']).lower()}) ON CONFLICT (id) DO NOTHING;")
    open(dest, "w").write("\n".join(out) + "\n")
    print(f"wrote {dest}")


def main(pdf, dest):
    try:
        pages, engine = pages_docling(pdf), "docling"
    except ImportError:
        pages, engine = pages_pdftotext(pdf), "pdftotext"
    with open(dest, "w") as f:
        for n, text in enumerate(pages, 1):
            f.write(f"<!-- page {n} -->\n{text.strip(chr(10))}\n\n")
    print(f"{engine}: wrote {len(pages)} pages to {dest}")


if __name__ == "__main__":
    if sys.argv[1] == "--sync":
        sync(*sys.argv[2:4])
    elif sys.argv[1] == "--sql":
        sql(*sys.argv[2:4])
    else:
        main(*sys.argv[1:3])
